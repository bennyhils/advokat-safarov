import type { Payload } from 'payload'

import { SAFAROV, SAFAROV_REVIEWS } from './content/safarov'

export async function seedIfNeeded(payload: Payload) {
  const users = await payload.find({ collection: 'users', limit: 1 })
  if (users.totalDocs === 0) {
    await payload.create({
      collection: 'users',
      data: {
        email: process.env.ADMIN_EMAIL || 'admin@advokat.local',
        password: process.env.ADMIN_PASSWORD || 'admin12345',
        name: 'Администратор',
      },
    })
    payload.logger.info('Создан администратор. Войдите в /admin')
  }

  const services = await payload.find({ collection: 'services', limit: 1 })
  if (services.totalDocs > 0) {
    return
  }

  await payload.updateGlobal({
    slug: 'settings',
    data: SAFAROV,
  })

  const serviceItems = [
    {
      title: 'Уголовные дела',
      excerpt: 'Защита на следствии и в суде, работа со свидетелями, смягчение наказания.',
      content:
        'Представляю интересы подозреваемых, обвиняемых и потерпевших. Вступаю в дело на любой стадии: задержание, следствие, судебное разбирательство, апелляция.',
    },
    {
      title: 'Семейные споры',
      excerpt: 'Развод, раздел имущества, алименты, определение места жительства детей.',
      content:
        'Помогаю пройти семейный конфликт без лишней эскалации, но с защитой ваших интересов в суде, если переговоры невозможны.',
    },
    {
      title: 'ДТП и страховые споры',
      excerpt: 'Возмещение ущерба, споры с страховой, защита при обвинении в нарушении ПДД.',
      content:
        'Собираю доказательства, готовлю претензии и иски, представляю интересы в ГИБДД и суде.',
    },
    {
      title: 'Наследственные дела',
      excerpt: 'Оформление наследства, споры между наследниками, восстановление срока.',
      content:
        'Помогаю принять наследство, оспорить завещание и урегулировать конфликт между родственниками.',
    },
    {
      title: 'Сопровождение бизнеса',
      excerpt: 'Договоры, споры с контрагентами, налоговые риски, арбитраж.',
      content:
        'Работаю с предпринимателями и компаниями: от разовой консультации до представительства в арбитражном суде.',
    },
    {
      title: 'Мошенничество и экономические статьи',
      excerpt: 'Защита по делам о мошенничестве, присвоении, налоговых преступлениях.',
      content:
        'Экономические составы требуют аккуратной работы с документами и экспертизами. Разбираю материалы и выстраиваю линию защиты.',
    },
  ]

  for (const [index, item] of serviceItems.entries()) {
    await payload.create({
      collection: 'services',
      data: { ...item, order: index + 1, published: true },
    })
  }

  await payload.create({
    collection: 'cases',
    data: {
      title: 'Прекращение уголовного дела на следствии',
      result: 'Дело прекращено',
      excerpt:
        'Доверителя обвиняли в преступлении небольшой тяжести. После работы с доказательствами следствие прекратило преследование.',
      content:
        'На стадии следствия удалось показать неустранимые противоречия в показаниях и поставить под сомнение ключевую экспертизу. Дело прекращено по реабилитирующему основанию.',
      published: true,
    },
  })

  await payload.create({
    collection: 'cases',
    data: {
      title: 'Определение места жительства ребёнка',
      result: 'Иск удовлетворён',
      excerpt:
        'Суд определил место жительства ребёнка с отцом и установил порядок общения с матерью.',
      content:
        'Собрали характеристики, сведения об условиях проживания и графике работы. Суд согласился с предложенным графиком общения.',
      published: true,
    },
  })

  await payload.create({
    collection: 'cases',
    data: {
      title: 'Взыскание ущерба после ДТП',
      result: 'Взыскано 840 000 ₽',
      excerpt:
        'Страховая занизила выплату. Через независимую экспертизу и суд взыскали недостающую сумму и расходы.',
      content:
        'После досудебной претензии страховая отказала. В суде подтвердили размер ущерба заключением эксперта.',
      published: true,
    },
  })

  await payload.create({
    collection: 'posts',
    data: {
      title: 'Что делать, если вызвали на допрос',
      excerpt: 'Коротко: не ходите без адвоката и не подписывайте то, чего не понимаете.',
      content:
        'Повестка на допрос — не повод паниковать, но и не формальность. Имеет смысл заранее обсудить ситуацию с адвокатом, понять статус (свидетель, подозреваемый) и свои права. На допросе можно пользоваться статьёй 51 Конституции и не давать показания против себя.',
      published: true,
      publishedAt: new Date().toISOString(),
    },
  })

  await payload.create({
    collection: 'posts',
    data: {
      title: 'Как готовиться к консультации адвоката',
      excerpt: 'Хронология событий, документы и ваши вопросы экономят час разговора.',
      content:
        'Перед встречей соберите документы, составьте хронологию и список вопросов. Так консультация будет предметной, а оценка перспектив — точнее.',
      published: true,
      publishedAt: new Date(Date.now() - 86400000 * 7).toISOString(),
    },
  })

  for (const review of SAFAROV_REVIEWS) {
    await payload.create({
      collection: 'reviews',
      data: {
        ...review,
        published: true,
      },
    })
  }

  payload.logger.info('Заполнены демо-данные сайта')
}
